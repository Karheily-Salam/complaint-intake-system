async def test_d_invalid_user_id_correction_is_clear_and_field_specific():
    """Engine-level check (see test_engine_merge.py for the exact invalid
    value) is not enough on its own since the rule-based extractor can't
    normally produce an invalid user_id (any extracted token already
    satisfies its length bounds) - this drives the same phrasing path via
    the reply layer directly, matching what compose_reply produces for an
    invalid user_id regardless of how it became invalid.
    """
    provider = RuleBasedAIProvider()
    request = ReplyRequest(
        kind=ReplyKind.ASK,
        complaint_label="Withdrawal problem",
        customer_name="Jane",
        language_code="ar",
        invalid_fields=[
            InvalidField(key="user_id", label="User ID", error="Must be at least 2 characters.")
        ],
    )
    draft = await provider.compose_reply(request)
    _assert_clean(draft.body)
    assert "رقم المستخدم" in draft.body
    assert "غير صحيح" in draft.body


