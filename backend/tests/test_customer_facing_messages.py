"""Customer-facing wording must be natural, language-appropriate, and free of
internal system details:

  - invalid-field corrections must not expose the raw schema key (e.g.
    "account_email") or the raw English validation error text (e.g. "Please
    check this value."/"Not a valid email address.") - see
    RuleBasedAIProvider._field_invalid_message / _FIELD_INVALID_PHRASES.
  - the final ticket confirmation must not expose the raw internal
    classification label (e.g. "withdrawal problem") and must instead show
    the actual collected values under natural, localized labels - see
    ConversationEngine.compose_ticket_confirmation /
    RuleBasedAIProvider._FIELD_DISPLAY_LABELS.
  - the ticket reference is numeric-only, generated by TicketService from the
    ticket's own database primary key (never by the AI) - see
    TicketService._make_reference.

None of this changes the underlying deterministic pending-field / invalid-
field workflow (see test_pending_field_context.py and
test_pending_field_invalid_priority.py, which continue to pass unchanged).
"""

from __future__ import annotations

from fastapi.testclient import TestClient

from app.ai.base import InvalidField, ReplyKind, ReplyRequest
from app.ai.providers.rule_based import RuleBasedAIProvider

_WITHDRAWAL_OPENER_AR = (
    "مرحبا، لدي مشكلة في سحب الأموال. طلبت السحب أمس ولكن المال لم يصل إلى حسابي."
)

# Internal schema keys that must never appear verbatim in a customer-facing
# reply, in any language.
_INTERNAL_KEYS = (
    "account_email",
    "user_id",
    "withdrawal_transaction_id",
    "transaction_date",
    "source_wallet_or_account",
    "deposit_method",
    "problem_description",
)

# Raw English validation-error fragments the old implementation used to leak
# straight into every language's correction message.
_RAW_VALIDATION_PHRASES = (
    "Please check this value",
    "Not a valid email address",
    "Must be at least",
    "Not a recognisable date",
)


def send(
    client: TestClient,
    body: str,
    *,
    conversation_id: int | None = None,
    from_addr: str,
    name: str | None = "Jane",
) -> dict:
    payload: dict = {"from_addr": from_addr, "body": body, "customer_name": name}
    if conversation_id is not None:
        payload["conversation_id"] = conversation_id
    resp = client.post("/api/v1/inbox", json=payload)
    assert resp.status_code == 201, resp.text
    return resp.json()


def _assert_clean(reply_body: str) -> None:
    for key in _INTERNAL_KEYS:
        assert key not in reply_body, f"internal key {key!r} leaked into: {reply_body!r}"
    for phrase in _RAW_VALIDATION_PHRASES:
        assert phrase not in reply_body, (
            f"raw validation text {phrase!r} leaked into: {reply_body!r}"
        )


