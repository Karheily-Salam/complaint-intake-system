def test_a_arabic_invalid_account_email_gets_a_clear_correction(client):
    addr = "a-ar-invalid-email@example.com"
    r1 = send(client, _WITHDRAWAL_OPENER_AR, from_addr=addr)
    cid = r1["conversation"]["id"]
    send(client, "111", conversation_id=cid, from_addr=addr)

    r3 = send(client, "سيلبمنتى@سيل", conversation_id=cid, from_addr=addr)
    assert r3["conversation"]["pending_field"] == "account_email"
    assert r3["is_complete"] is False
    _assert_clean(r3["reply_body"])
    # Natural, specific Arabic correction - not a generic placeholder.
    assert "البريد الإلكتروني" in r3["reply_body"]
    assert "example@example.com" in r3["reply_body"]


