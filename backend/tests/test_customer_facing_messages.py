def test_j_reference_is_numeric_persisted_and_never_invented_by_ai(client):
    addr = "j-reference-integrity@example.com"
    r1 = send(
        client,
        "I cannot withdraw my money and it has been stuck for two days. "
        "User ID: 111. Account email: customer@example.com. Transaction ID: WD-1.",
        from_addr=addr,
    )
    assert r1["is_complete"] is True
    ref = r1["ticket_reference"]
    assert ref is not None
    assert ref.isdigit()
    assert "-" not in ref

    # The exact same reference is returned by the dashboard/API lookup - the
    # AI only ever phrases a reference the service already generated and
    # persisted; it never invents or alters it.
    ticket = client.get(f"/api/v1/tickets/{ref}").json()
    assert ticket["reference"] == ref
    assert ref in r1["reply_body"]

    tickets = client.get("/api/v1/tickets").json()
    assert any(t["reference"] == ref for t in tickets)


def test_j_two_tickets_get_distinct_numeric_references(client):
    r_a = send(
        client,
        "I cannot withdraw my money and it has been stuck for two days. "
        "User ID: 11. Account email: a@example.com. Transaction ID: WD-1.",
        from_addr="j-a@example.com",
    )
    r_b = send(
        client,
        "I cannot withdraw my money and it has been stuck for two days. "
        "User ID: 22. Account email: b@example.com. Transaction ID: WD-2.",
        from_addr="j-b@example.com",
    )
    assert r_a["ticket_reference"].isdigit()
    assert r_b["ticket_reference"].isdigit()
    assert r_a["ticket_reference"] != r_b["ticket_reference"]
